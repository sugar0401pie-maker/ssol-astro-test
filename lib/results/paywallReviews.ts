/** 화면을 열 때 한 번 섞는다(같은 후기가 연달아 나오지 않게 순서대로 돌림) */
export function shuffled<T>(list: readonly T[], rand: () => number = Math.random): T[] {
  const a = [...list];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
